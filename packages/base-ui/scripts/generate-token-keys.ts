import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export type ExtractedThemeTokens = Record<
  string,
  { cssVariable: `--ov-${string}`; valueKind: 'color' | 'font-style' }
>;

const THEME_VAR_RE = /(--ov-(color|syntax)-([a-z0-9-]+))\s*:/g;

export function extractThemeTokens(css: string): ExtractedThemeTokens {
  const result: ExtractedThemeTokens = {};
  for (const match of css.matchAll(THEME_VAR_RE)) {
    const cssVariable = match[1] as `--ov-${string}`;
    const prefix = match[2];
    const rest = match[3];
    if (!rest) continue;
    const key = `${prefix}.${rest.replaceAll('-', '.')}`;
    result[key] = {
      cssVariable,
      valueKind: key.startsWith('syntax.style.') ? 'font-style' : 'color',
    };
  }
  return Object.fromEntries(Object.entries(result).sort(([a], [b]) => a.localeCompare(b)));
}

export function renderTypesFile(tokens: ExtractedThemeTokens): string {
  const entries = Object.entries(tokens).sort(([a], [b]) => a.localeCompare(b));
  const union = entries.length === 0 ? 'never' : entries.map(([key]) => `  | '${key}'`).join('\n');
  const metadata = entries
    .map(
      ([key, value]) =>
        `  '${key}': { cssVariable: '${value.cssVariable}', valueKind: '${value.valueKind}' },`,
    )
    .join('\n');

  return `// AUTO-GENERATED by scripts/generate-token-keys.ts. Do not edit by hand.
// Regenerate with: pnpm generate:token-keys

export type ThemeTokenValueKind = 'color' | 'font-style';

export type ThemeTokenKey =
${union};

export const THEME_TOKEN_METADATA: Readonly<
  Record<ThemeTokenKey, { cssVariable: \`--ov-\${string}\`; valueKind: ThemeTokenValueKind }>
> = Object.freeze({
${metadata}
});
`;
}

function main() {
  const here = resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
  const input = readFileSync(resolve(here, 'src/theme/styles.css'), 'utf8');
  const output = resolve(here, 'src/theme/generated/tokenKeys.ts');
  const tokens = extractThemeTokens(input);
  const content = renderTypesFile(tokens);
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, content, 'utf8');
  console.log(`Generated ${output} (${Object.keys(tokens).length} theme tokens)`);
}

// ESM-compatible entrypoint guard: only run main() when executed directly via tsx/node.
// import.meta.url is the file's URL; process.argv[1] is the executed file path.
if (import.meta.url === new URL(process.argv[1] ?? '', 'file:').href) {
  main();
}
